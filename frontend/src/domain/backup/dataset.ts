/**
 * Milestone 6 — BappDataset: an in-memory TRANSPORT / REPORTING representation
 * of the accepted authoritative records.
 *
 * IMPORTANT (locked): BappDataset is NOT a source of truth. It is a read-only
 * projection used by Statistics, Export, Import/Merge planning, Restore and
 * Diagnostics. The authoritative records remain:
 *   - DB-001 rounds      = raw baccarat history
 *   - DB-001 revisions   = history revision audit
 *   - DB-002 locked_prediction_entries = historical decision audit
 *   - DB-002 session_state = workflow metadata only
 *
 * Historical locked predictions are copied VERBATIM (immutable payload). They
 * are NEVER regenerated by current engine code when a dataset is built.
 */
import type { RoundRecord } from '../models/round';
import type { RevisionRecord, ShoeRecord } from '../models/records';

/** Mirror of a `locked_prediction_entries` row (camelCase transport form). */
export interface LockedPredictionEntryRecord {
  readonly id: string;
  readonly shoeId: string;
  readonly targetRoundNumber: number;
  readonly sequenceIndex: number;
  readonly status: string;
  readonly decision: string;
  readonly side: string | null;
  readonly confidence: number;
  readonly category: string;
  /** 'UNSET' | 'PLAYED' | 'NOT_PLAYED' */
  readonly operatorAction: string;
  /** StepResult: PENDING | WIN | LOSS | PUSH | SKIPPED | INVALIDATED */
  readonly evaluation: string;
  readonly actualWinner: string | null;
  readonly invalidated: boolean;
  readonly invalidatedByRevisionId: string | null;
  readonly invalidatedAt: string | null;
  readonly lockedAt: string;
  readonly evaluatedAt: string | null;
  readonly payloadVersion: string;
  /** Immutable locked-prediction JSON payload — copied verbatim, never rebuilt. */
  readonly payload: string;
  readonly createdAt: string;
}

/** Mirror of a `session_state` row (workflow metadata only). */
export interface SessionStateRecord {
  readonly shoeId: string;
  readonly sessionVersion: string;
  readonly workflow: string;
  readonly environment: string;
  readonly currentTargetRound: number | null;
  readonly paperUnitsStaked: number;
  readonly paperNetUnits: number;
  readonly paperWins: number;
  readonly paperLosses: number;
  readonly paperPushes: number;
  readonly createdAt: string;
  readonly updatedAt: string;
}

/** The full in-memory projection of the authoritative records. */
export interface BappDataset {
  readonly shoes: readonly ShoeRecord[];
  readonly rounds: readonly RoundRecord[];
  readonly revisions: readonly RevisionRecord[];
  readonly lockedPredictions: readonly LockedPredictionEntryRecord[];
  readonly sessionStates: readonly SessionStateRecord[];
}

export const EMPTY_DATASET: BappDataset = Object.freeze({
  shoes: [],
  rounds: [],
  revisions: [],
  lockedPredictions: [],
  sessionStates: [],
});
